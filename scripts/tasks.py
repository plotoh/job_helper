'''

У тебя есть список строк — сырые логи в формате "2024-01-15 ERROR Database timeout".
Напиши функцию parse_logs(logs), которая:

Разбирает каждую строку на дату, уровень и сообщение.

Возвращает список словарей {'date': ..., 'level': ..., 'message': ...}.

Оставляет только логи с уровнем ERROR.

Цель: попрактиковаться в split, работе со словарями и фильтрации.

'''


def parse_log(string: str) -> dict:
    log = string.split(' ')
    return {
        'date': log[0],
        'level': log[1],
        'message': log[2:],
    }


def get_logs(logs: list, err_type="ERROR") -> list:
    return [parse_log(el) for el in logs]


